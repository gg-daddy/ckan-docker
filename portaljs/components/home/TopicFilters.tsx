export default function TopicFilters({ topics, selectedTopic, maxDisplay = 8 }: TopicFiltersProps) {
  const displayTopics = topics.slice(0, maxDisplay);
  const hasMore = topics.length > maxDisplay;

  if (topics.length === 0) {
    return null;
  }

  return (
    <div className="flex flex-wrap justify-center gap-3">
      {/* All topics button */}
      <Link
        href="/search"
        className={!selectedTopic ? 'topic-btn-active' : 'topic-btn-default'}
      >
        <svg className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 6h16M4 10h16M4 14h16M4 18h16" />
        </svg>
        All Topics
      </Link>

      {/* Topic buttons */}
      {displayTopics.map((topic) => (
        <Link
          key={topic.name}
          href={`/search?tags=${encodeURIComponent(topic.name)}`}
          className={selectedTopic === topic.name ? 'topic-btn-active' : 'topic-btn-default'}
        >
          {getTopicIcon(topic.name)}
          <span>{topic.display_name}</span>
          <span className="text-xs opacity-60">({topic.count})</span>
        </Link>
      ))}

      {/* Show more button */}
      {hasMore && (
        <Link
          href="/search"
          className="topic-btn-default"
        >
          <svg className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 6v6m0 0v6m0-6h6m-6 0H6" />
          </svg>
          More Topics
        </Link>
      )}
    </div>
  );
}
